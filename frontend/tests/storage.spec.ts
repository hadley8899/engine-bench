import { expect, test } from '@playwright/test'
import type { Run } from '../src/sim/schema'

// Only the isolated API/test database on :8003 is allowed for these writes.
if (process.env.BENCH_STORAGE_E2E === '1' &&
    (process.env.BENCH_URL !== 'http://127.0.0.1:5180' || process.env.API_PROXY_TARGET !== 'http://127.0.0.1:8003'))
  throw new Error('Storage browser tests require the isolated frontend/API. Use scripts/test-storage-browser.sh.')
test.skip(process.env.BENCH_STORAGE_E2E !== '1', 'Run scripts/test-storage-browser.sh with its isolated API and test database.')

test('guest experiment survives sign-in; revisions, immutable history and reruns survive reload', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  const name = `Browser ${test.info().project.name} ${Date.now()}`
  const experiment = async () => page.evaluate(() => JSON.parse(sessionStorage.getItem('engine-bench:guest-experiment:1')!))
  await page.goto('/')
  await page.getByLabel('Build name', { exact: true }).fill(name)
  await page.getByRole('button', { name: 'Stop & rebuild engine', exact: true }).click()
  await page.getByLabel('End RPM', { exact: true }).fill('2500')
  await page.getByRole('button', { name: 'Quick test', exact: true }).click()
  await expect(page.getByTestId('run-summary')).toContainText('COMPLETE')
  const baseline: Run = (await experiment()).baseline
  await page.getByLabel('Bore (mm)', { exact: true }).fill('88')
  await page.getByRole('link', { name: 'Sign in to save builds & runs' }).click()
  await page.getByLabel('Email', { exact: true }).fill('admin@example.test')
  await page.getByLabel('Password', { exact: true }).fill('password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Saved builds & runs' })).toBeVisible()
  await expect(page.getByLabel('Bore (mm)', { exact: true })).toHaveValue('88')
  expect((await experiment()).baseline).toEqual(baseline)
  await page.getByRole('button', { name: 'Stop & rebuild engine', exact: true }).click()
  await page.getByLabel('Save to workspace').click()
  await page.getByRole('option', { name: /personal/ }).click()
  await expect(page.getByRole('button', { name: 'Save as new build', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Save as new build', exact: true }).click()
  await expect(page.getByText(`Saved ${name}, revision 1`, { exact: false })).toBeVisible()
  await page.getByLabel('Bore (mm)', { exact: true }).fill('90')
  await page.getByRole('button', { name: 'Stop & rebuild engine', exact: true }).click()
  await page.getByRole('button', { name: 'Save new revision', exact: true }).click()
  await expect(page.getByText(`Saved ${name}, revision 2`, { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Save baseline run', exact: true }).click()
  await expect(page.getByText('Baseline saved with revision 1.', { exact: false })).toBeVisible()
  // Saving an older snapshot again must reuse its saved revision, even after reload.
  await page.reload()
  await expect(page.getByRole('button', { name: 'Save baseline run', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Save baseline run', exact: true }).click()
  await expect(page.getByText('Baseline saved with revision 1.', { exact: false })).toBeVisible()
  const history = page.locator('.run-entry').filter({ hasText: name })
  await expect(history).toHaveCount(1)
  await history.getByRole('button', { name: 'Load as baseline' }).click()
  expect((await experiment()).baseline).toEqual(baseline)
  const build = page.locator('.library-entry').filter({ hasText: name }).filter({ has: page.getByRole('button', { name: 'Load build', exact: true }) }).filter({ hasText: 'Revision 2' })
  await build.getByRole('button', { name: 'Load build', exact: true }).click()
  await expect(page.getByLabel('Bore (mm)', { exact: true })).toHaveValue('90')
  await page.getByLabel('Historical revision', { exact: true }).fill('1')
  await page.getByRole('button', { name: 'Load revision', exact: true }).click()
  await expect(page.getByLabel('Bore (mm)', { exact: true })).toHaveValue('88')
  await history.getByRole('button', { name: 'Rerun into Modified', exact: true }).click()
  await expect(page.getByTestId('run-summary')).toContainText('COMPLETE')
  await expect.poll(async () => (await experiment()).modified?.status).toBe('complete')
  const rerun: Run = (await experiment()).modified
  expect(rerun.engine).toEqual(baseline.engine)
  expect(rerun.conditions).toEqual(baseline.conditions)
  expect(rerun.procedure).toEqual(baseline.procedure)
  expect(rerun.samples).toEqual(baseline.samples)
  expect(rerun.id).not.toBe(baseline.id)
  await page.getByLabel('New team name', { exact: true }).fill(`${name} team`)
  await page.getByRole('button', { name: 'Create team workspace', exact: true }).click()
  await expect(page.getByText('No saved builds yet.', { exact: false })).toBeVisible()
  await expect(page.getByText('No saved runs yet.', { exact: false })).toBeVisible()
  expect((await experiment()).baseline).toEqual(baseline)
  expect((await experiment()).modified).toEqual(rerun)
  await page.getByLabel('Save to workspace').click()
  await page.getByRole('option', { name: /personal/ }).click()
  await expect(page.locator('.run-entry').filter({ hasText: name })).toHaveCount(1)
  if (test.info().project.name === 'chromium') {
    await page.setViewportSize({ width: 1440, height: 1100 })
    await page.locator('.saved-library').screenshot({ path: '/tmp/engine-bench-library.png' })
  }
  expect(errors).toEqual([])
})
